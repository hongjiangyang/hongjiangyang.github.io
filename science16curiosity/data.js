export function score(answers){return axes.map((_,axis)=>{const items=questions.filter(q=>q.axis===axis);if(items.some(q=>!Number.isInteger(answers[q.id])||Math.abs(answers[q.id])>3))throw Error('Please complete every question.');return items.reduce((s,q)=>s+answers[q.id]*q.sign,0)/(items.length*3);});}
export function classify(scores,ties={}){const bits=scores.map((v,i)=>v===0?ties[i]:Number(v>0));if(bits.some(v=>v!==0&&v!==1))return null;return types.find(t=>t.bits.every((v,i)=>v===bits[i]));}
export function clarity(scores){return Math.round(scores.reduce((s,v)=>s+Math.abs(v),0)/4*100);}
